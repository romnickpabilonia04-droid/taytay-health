<?php
require_once "../config/database.php";
require_once "../includes/auth.php";
requireAdmin();

$notifications = $conn->query("
    SELECT n.notification_id, n.message, n.is_read, n.created_at,
           u.full_name, u.email, n.appointment_id
    FROM notifications n
    JOIN users u ON n.user_id = u.user_id
    ORDER BY n.created_at DESC
");
?>
<?php
$pageTitle = "Admin Notifications";
require_once "../includes/header.php";
?>
    <h1>Notification Center</h1>
    <p>Notifications generated by patient bookings and appointment status updates.</p>

    <div class="table-container">
        <table>
            <thead>
                <tr><th>ID</th><th>Patient</th><th>Message</th><th>Appointment</th><th>Read</th><th>Date</th></tr>
            </thead>
            <tbody>
            <?php if ($notifications->num_rows > 0): ?>
                <?php while ($n = $notifications->fetch_assoc()): ?>
                    <tr>
                        <td><?= (int)$n["notification_id"] ?></td>
                        <td>
                            <?= htmlspecialchars($n["full_name"]) ?><br>
                            <small><?= htmlspecialchars($n["email"]) ?></small>
                        </td>
                        <td><?= htmlspecialchars($n["message"]) ?></td>
                        <td><?= $n["appointment_id"] ? "#" . (int)$n["appointment_id"] : "—" ?></td>
                        <td><?= $n["is_read"] ? "Read" : "Unread" ?></td>
                        <td><?= date("M d, Y h:i A", strtotime($n["created_at"])) ?></td>
                    </tr>
                <?php endwhile; ?>
            <?php else: ?>
                <tr><td colspan="6">No notifications yet.</td></tr>
            <?php endif; ?>
            </tbody>
        </table>
    </div>
<?php require_once "../includes/footer.php"; ?>